from datetime import datetime
from pathlib import Path

from verdict.core.models import (
    Direction,
    KeyEvent,
    Platform,
    RecordingHandle,
    Selector,
    UiHierarchy,
)
from verdict.device_driver.base import (
    AppLifecycleDriver,
    DeviceDriver,
    DiagnosticsDriver,
    InputDriver,
)


class _FullDriver:
    platform = Platform.ANDROID

    def tap(self, x: int, y: int) -> None: ...
    def tap_selector(self, selector: Selector) -> None: ...
    def swipe(self, x1: int, y1: int, x2: int, y2: int, duration_ms: int = 300) -> None: ...
    def scroll(self, direction: Direction, selector: Selector | None = None) -> None: ...
    def type_text(self, text: str) -> None: ...
    def type_keys(self, text: str, interval_ms: int = 150) -> None: ...
    def press_key(self, key: KeyEvent) -> None: ...
    def screenshot(self) -> Path: ...
    def dump_hierarchy(self) -> UiHierarchy: ...
    def get_text(self, selector: Selector) -> str | None: ...
    def wait_for(self, selector: Selector, timeout_ms: int) -> bool: ...

    def install(self, path: str) -> None: ...
    def uninstall(self, package: str) -> None: ...
    def launch(self, package: str, activity: str | None = None) -> None: ...
    def clear_data(self, package: str) -> None: ...

    def collect_logs(self, since: datetime | None = None) -> Path: ...
    def start_recording(self) -> RecordingHandle: ...
    def stop_recording(self, handle: RecordingHandle) -> Path: ...
    def collect_bugreport(self) -> Path | None: ...


class _InputOnlyDriver:
    def tap(self, x: int, y: int) -> None: ...
    def tap_selector(self, selector: Selector) -> None: ...
    def swipe(self, x1: int, y1: int, x2: int, y2: int, duration_ms: int = 300) -> None: ...
    def scroll(self, direction: Direction, selector: Selector | None = None) -> None: ...
    def type_text(self, text: str) -> None: ...
    def type_keys(self, text: str, interval_ms: int = 150) -> None: ...
    def press_key(self, key: KeyEvent) -> None: ...
    def screenshot(self) -> Path: ...
    def dump_hierarchy(self) -> UiHierarchy: ...
    def get_text(self, selector: Selector) -> str | None: ...
    def wait_for(self, selector: Selector, timeout_ms: int) -> bool: ...


def test_full_driver_satisfies_composed_protocol():
    driver = _FullDriver()
    assert isinstance(driver, InputDriver)
    assert isinstance(driver, AppLifecycleDriver)
    assert isinstance(driver, DiagnosticsDriver)
    assert isinstance(driver, DeviceDriver)


def test_input_only_driver_satisfies_input_but_not_composed():
    driver = _InputOnlyDriver()
    assert isinstance(driver, InputDriver)
    assert not isinstance(driver, AppLifecycleDriver)
    assert not isinstance(driver, DeviceDriver)
